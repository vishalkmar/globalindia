export { DISPATCH };

/** Map a compact seed row to Product data (validated with the same schema the admin uses). */
export function productData(p, categoryId, order, productSchema) {
  const specs = (p.specs ?? []).map(([property, value, method]) => ({ property, value, method }));
  const parsed = productSchema.safeParse({
    name: p.n,
    slug: p.s,
    categoryId,
    casNo: p.cas ?? "",
    grade: p.g ?? "",
    purity: p.p ?? "",
    form: p.f ?? "",
    packSizes: p.pk ?? [],
    moq: p.moq ?? "",
    shelfLife: p.life ?? "",
    dispatchTime: DISPATCH,
    applications: p.apps ?? [],
    summary: p.sum ?? "",
    specs,
    faqs: HERO_FAQS[p.s] ?? [],
    brandNote: p.brand ?? "",
    isSourced: p.src !== false,
    featured: Boolean(p.feat),
    status: "PUBLISHED",
  });
  if (!parsed.success)
    throw new Error(
      `Seed product ${p.s} is invalid: ${parsed.error.issues[0].path.join(".")} ${parsed.error.issues[0].message}`,
    );
  const { gallery: _g, documents: _d, ...data } = parsed.data;
  return { ...data, order, publishedAt: new Date() };
}

/**
 * Creates the categories and products that do not exist yet (matched by slug). Existing rows are
 * never overwritten, so admin edits survive a re-seed.
 */
export async function seedCatalogue(db, { categorySchema, productSchema }, log) {
  const ids = {};
  let newCats = 0;
  for (const [i, [slug, name, family, intro]] of CATEGORIES.entries()) {
    const extra = CATEGORY_GUIDES[slug] ?? {};
    const existing = await db.productCategory.findUnique({ where: { slug }, select: { id: true, guide: true } });
    if (existing) {
      ids[slug] = existing.id;
      // Fill an empty buying guide once; anything the admin wrote is never replaced.
      if (!existing.guide && extra.guide) {
        await db.productCategory.update({ where: { id: existing.id }, data: { guide: extra.guide, faqs: extra.faqs ?? [] } });
      }
      continue;
    }
    const data = categorySchema.parse({ slug, name, family, intro, status: "PUBLISHED", ...extra });
    ids[slug] = (await db.productCategory.create({ data: { ...data, order: i } })).id;
    newCats += 1;
  }
  let newProducts = 0;
  const orderIn = {};
  for (const p of PRODUCTS) {
    orderIn[p.c] = (orderIn[p.c] ?? -1) + 1;
    if (await db.product.findUnique({ where: { slug: p.s }, select: { id: true } })) continue;
    await db.product.create({ data: productData(p, ids[p.c], orderIn[p.c], productSchema) });
    newProducts += 1;
  }
  log(
    "catalogue",
    `${newCats} new categories, ${newProducts} new products (${CATEGORIES.length} / ${PRODUCTS.length} in the seed list)`,
  );
}
